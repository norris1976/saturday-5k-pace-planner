// Regenerates src/agegrade-data.js from data/AgeGrade.5k (the plain-text 5 km factor file
// published in the CC0 Age-Grade-Tables repository, 2025 edition). Run: npm run gen-data
import { readFileSync, writeFileSync } from 'node:fs';
const lines = readFileSync(new URL('../data/AgeGrade.5k', import.meta.url), 'utf8').split(/\r?\n/).filter(Boolean);
const open = {}; const factors = { M: {}, F: {} };
for (const l of lines) {
  const p = l.trim().split(/\s+/);
  if (p[1].includes(':')) { const [h, m, s] = p[1].split(':').map(Number); open[p[0]] = h * 3600 + m * 60 + s; }
  else factors[p[0]][Number(p[1])] = Number(p[2]);
}
const fmt = (o) => '{' + Object.entries(o).map(([k, v]) => `${k}:${v}`).join(',') + '}';
const out = `// GENERATED by tools/gen-data.mjs from data/AgeGrade.5k. Do not edit by hand.
// Source: road running age-grade tables 2025 edition, Alan Jones (with Tom Bernhard), CC0 1.0.
// https://github.com/AlanLyttonJones/Age-Grade-Tables (commit 4aac6737cb9f216c90a0a610355667cd3d921c61)
export const OPEN_STANDARD_SEC = ${JSON.stringify(open)};
export const AGE_FACTORS = {
  M: ${fmt(factors.M)},
  F: ${fmt(factors.F)},
};
`;
writeFileSync(new URL('../src/agegrade-data.js', import.meta.url), out);
console.log('wrote src/agegrade-data.js', Object.keys(factors.M).length, Object.keys(factors.F).length);
